// ignore_for_file: avoid_print
//
// 生成 AnyParser：根据 lib/common/models/server_client 下 protoc 生成的 *.pb.dart，
// 建立 `google.protobuf.Any.typeUrl` -> Message 构造器 的映射。
//
// 用法（项目根目录）：dart run scripts/build_any_parser.dart
// 建议在 scripts/build_proto.dart 生成 pb 之后执行。
import 'dart:io';

import 'package:path/path.dart' as p;

/// pb.dart 所在目录（相对项目根目录）
const List<String> kPbDir = ['lib', 'common', 'models', 'server_client'];

/// 生成文件路径（相对项目根目录）
const List<String> kOutputFile = ['lib', 'common', 'models', 'any_parser.dart'];

Directory findProject(Directory dir) {
  if (dir.listSync().any((e) => e is File && p.basename(e.path) == 'pubspec.yaml')) {
    return dir;
  } else if (dir.parent.path == dir.path) {
    throw 'Cannot find project path';
  } else {
    return findProject(dir.parent);
  }
}

void main(List<String> args) {
  File script = File.fromUri(Platform.script);

  Directory project = findProject(script.parent);
  // print('Project path: ${project.path}');

  final pbDir = Directory(p.joinAll([project.path, ...kPbDir]));
  if (!pbDir.existsSync()) {
    print('pb directory not found: ${pbDir.path}');
    exit(1);
  }

  final outputPath = p.joinAll([project.path, ...kOutputFile]);

  String content = generateContent(pbDir, p.dirname(outputPath));

  if (content.isEmpty) {
    print('No GeneratedMessage found in ${pbDir.path}');
    return;
  }

  File(outputPath).writeAsStringSync(content, flush: true);
  Process.runSync('dart', ['format', '--line-length=120', outputPath]);
  print('Generated file: $outputPath');
}

/// pbDir: 包含 *.pb.dart 的目录；outputDir: 生成文件所在目录（用于计算相对 import）
String generateContent(Directory pbDir, String outputDir) {
  final files = pbDir
      .listSync(recursive: true)
      .whereType<File>()
      .where((f) => f.path.endsWith('.pb.dart'))
      .toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  List<PbFile> pbFiles = [];
  for (File f in files) {
    PbFile? pbFile = _parsePbFile(f);
    if (pbFile != null) {
      pbFiles.add(pbFile);
    }
  }

  if (pbFiles.isEmpty) {
    return '';
  }

  List<String> lines = [];

  lines.add('''// GENERATED CODE - DO NOT MODIFY BY HAND
// Generated by scripts/build_any_parser.dart
// ignore_for_file: lines_longer_than_80_chars, avoid_print, library_prefixes, no_leading_underscores_for_library_prefixes
import 'package:protobuf/protobuf.dart';
import 'package:protobuf/well_known_types/google/protobuf/any.pb.dart';
''');

  // 每个 pb 文件使用独立前缀，避免不同 package 下同名 message 冲突
  for (int i = 0; i < pbFiles.length; i++) {
    final importPath = p.posix.joinAll(p.split(p.relative(pbFiles[i].file.path, from: outputDir)));
    lines.add("import '$importPath' as \$$i;");
  }

  lines.add('''

typedef GeneratedMessageBuilder<T extends GeneratedMessage> = T Function();

class AnyParser {
  AnyParser._();

  static T? parse<T extends GeneratedMessage>(Any any) {
    String typeUrl = any.typeUrl;
    String typeName = typeUrl.substring(typeUrl.indexOf('/') + 1);
    GeneratedMessage? type = _types[typeName]?.call();
    if (type == null) {
      print('Unknown type: \$typeName');
      return null;
    }
    type.mergeFromBuffer(any.value);
    return type as T;
  }

  static final TypeRegistry typeRegistry = TypeRegistry(_types.values.map((f) => f()));

  static final Map<String, GeneratedMessageBuilder> _types = {''');

  final Set<String> added = {};
  for (int i = 0; i < pbFiles.length; i++) {
    for (PbMessage msg in pbFiles[i].messages) {
      if (!added.add(msg.fullName)) {
        print('Duplicate message ignored: ${msg.fullName} (${pbFiles[i].file.path})');
        continue;
      }
      lines.add("    '${msg.fullName}': () => \$$i.${msg.className}.create(),");
    }
  }

  lines.add('  };');
  lines.add('}');
  lines.add('');

  return lines.join('\n');
}

final RegExp _classReg = RegExp(r'class\s+(\w+)\s+extends\s+\$pb\.GeneratedMessage\b');

// 匹配 BuilderInfo 中的 message 名称与 package（兼容 dart format 换行）
final RegExp _builderInfoReg = RegExp(
  r"\$pb\.BuilderInfo\(\s*_omitMessageNames\s*\?\s*''\s*:\s*'([\w.]+)'\s*,"
  r"(?:\s*package:\s*const\s+\$pb\.PackageName\(\s*_omitMessageNames\s*\?\s*''\s*:\s*'([\w.]+)'\s*\))?",
);

PbFile? _parsePbFile(File pbFile) {
  final content = pbFile.readAsStringSync();
  final classMatches = _classReg.allMatches(content).toList();
  List<PbMessage> messages = [];

  for (int i = 0; i < classMatches.length; i++) {
    final m = classMatches[i];
    final end = i + 1 < classMatches.length ? classMatches[i + 1].start : content.length;
    final body = content.substring(m.end, end);
    final info = _builderInfoReg.firstMatch(body);
    if (info == null) {
      print('BuilderInfo not found: ${m.group(1)} (${pbFile.path})');
      continue;
    }
    final name = info.group(1)!;
    final package = info.group(2);
    messages.add(PbMessage(
      m.group(1)!,
      package == null || package.isEmpty ? name : '$package.$name',
    ));
  }

  if (messages.isEmpty) {
    return null;
  }
  return PbFile(pbFile, messages);
}

class PbFile {
  final File file;
  final List<PbMessage> messages;

  PbFile(this.file, this.messages);
}

class PbMessage {
  /// Dart 类名，如 `Outer_Inner`
  final String className;

  /// proto 完整名称（Any.typeUrl 中 `/` 之后部分），如 `room.Outer.Inner`
  final String fullName;

  PbMessage(this.className, this.fullName);
}
